#!/usr/bin/env python3
"""Lumen's launcher icons: two designs, each in several colours, all drawn here.

Writes, for every icon in ICONS, an adaptive icon (res/mipmap-anydpi-v26/<id>.xml) with its
background and foreground vectors (res/drawable/<id>_background.xml, _foreground.xml), the two
one-colour marks for themed icons and notifications, and a preview sheet (SVG) of them all.

    python3 tools/icons/launcher_icons.py            # writes into app/src/main/res
    python3 tools/icons/launcher_icons.py sheet.svg  # also writes the preview sheet there
    python3 tools/icons/launcher_icons.py sheet.svg icon.svg  # and the README's icon, to render
                                                              # with rsvg-convert into docs/images/icon.png

Everything is on Android's 108x108 adaptive canvas: the launcher shows the middle 72x72, and the
mark stays inside a 66-wide circle. The ids match LauncherIcon in data/LauncherIcon.kt and the activity
aliases in AndroidManifest.xml; adding an icon means adding it in all three.
"""
import os
import sys

RES = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "res")

# ---- Shapes: (kind, ...) tuples that both writers understand. --------------------------------

def circle_path(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z"

HILL_BACK = "M0,74C18,62 32,62 50,70C66,77 84,70 108,60V108H0Z"
HILL_FRONT = "M0,84C22,70 44,74 60,80C76,86 92,82 108,74V108H0Z"
# One petal: a capsule from the centre outwards, turned about the centre.
PETAL = "M43,41a11,11 0 0 1 22,0v8a11,11 0 0 1 -22,0z"
MONO_HILL = "M26,74C36,64 46,64 55,69C64,74 73,71 82,63V78a4,4 0 0 1 -4,4H30a4,4 0 0 1 -4,-4Z"


def first_light(sky, hills, sun="#FFF6DD"):
    """A photo of first light: a sun low in a graded sky, over two lines of hills."""
    background = [("linear", [(0.12, sky[0]), (0.42, sky[1]), (0.62, sky[2]), (0.75, sky[3])])]
    foreground = [
        ("glow", 56, 55, 26, sun, 0.75),
        ("path", circle_path(56, 55, 12), sun, 1.0, 0),
        ("path", HILL_BACK, hills[0], 1.0, 0),
        ("path", HILL_FRONT, hills[1], 1.0, 0),
    ]
    return background, foreground


def bloom(petals, paper, alpha=0.86):
    """Four petals of light opening from the centre."""
    background = [("linear", [(0.0, paper[0]), (1.0, paper[1])])]
    foreground = [("path", PETAL, colour, alpha, i * 90 + 45) for i, colour in enumerate(petals)]
    foreground.append(("path", circle_path(54, 54, 5.5), "#FFFFFF", 1.0, 0))
    return background, foreground


PAPER = ("#FFFFFF", "#EEF2FA")
INK = ("#1B1D24", "#0B0C10")

# id, name on the preview sheet, layers, which one-colour mark it uses.
ICONS = [
    ("ic_launcher", "First Light", first_light(("#2F6BFF", "#8E7BFF", "#FF9E8A", "#FFD08A"), ("#3D3AA8", "#1A1B55")), "sun"),
    ("ic_launcher_dusk", "Dusk", first_light(("#2A1B6B", "#8A3FD1", "#FF5E8A", "#FFB36B"), ("#4A1F7A", "#1E0F3D")), "sun"),
    ("ic_launcher_ocean", "Ocean", first_light(("#0B3C8C", "#1B8FD6", "#4FD6D0", "#C8F5E0"), ("#0F6A8A", "#08344F")), "sun"),
    ("ic_launcher_forest", "Forest", first_light(("#1F6B4A", "#4FB36B", "#C9E27A", "#FFF0A8"), ("#1F7A4A", "#0E3B26")), "sun"),
    ("ic_launcher_rose", "Rose", first_light(("#C2457A", "#F27BA0", "#FFB0A0", "#FFE0B8"), ("#A8336B", "#4A1238")), "sun"),
    ("ic_launcher_graphite", "Graphite", first_light(("#2B2F38", "#6B7280", "#B8BEC9", "#E8EAEE"), ("#3A3F4A", "#111318"), "#FFFFFF"), "sun"),
    ("ic_launcher_bloom", "Bloom", bloom(("#0A84FF", "#7B61FF", "#FF7A9C", "#FFB23E"), PAPER), "bloom"),
    ("ic_launcher_bloom_dark", "Bloom Dark", bloom(("#0A84FF", "#7B61FF", "#FF7A9C", "#FFB23E"), INK, 0.9), "bloom"),
    ("ic_launcher_bloom_ocean", "Bloom Ocean", bloom(("#0A84FF", "#22C1DC", "#3DDC97", "#5B6CFF"), PAPER), "bloom"),
    ("ic_launcher_bloom_sunset", "Bloom Sunset", bloom(("#FF5E5E", "#FF8A3D", "#FFC73D", "#FF6FA8"), PAPER), "bloom"),
]

MONO = {
    # The sun and one hill: also the notification icon.
    "sun": [("path", circle_path(54, 46, 11), "#FFFFFF", 1.0, 0), ("path", MONO_HILL, "#FFFFFF", 0.6, 0)],
    "bloom": [("path", PETAL, "#FFFFFF", 0.55, i * 90 + 45) for i in range(4)] + [("path", circle_path(54, 54, 5.5), "#FFFFFF", 1.0, 0)],
}
MONO_FILES = {"sun": "ic_launcher_monochrome", "bloom": "ic_launcher_monochrome_bloom"}

# ---- Android vector drawables. ---------------------------------------------------------------

def argb(colour, alpha=1.0):
    return "#%02X%s" % (round(alpha * 255), colour.lstrip("#").upper())


def vector(layers, comment):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {comment} Generated by tools/icons/launcher_icons.py: edit that, not this. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:aapt="http://schemas.android.com/aapt"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    for layer in layers:
        kind = layer[0]
        if kind == "linear":
            out += ['    <path android:pathData="M0,0h108v108h-108z">', '        <aapt:attr name="android:fillColor">',
                    '            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108">']
            out += [f'                <item android:offset="{offset}" android:color="{argb(colour)}" />' for offset, colour in layer[1]]
            out += ["            </gradient>", "        </aapt:attr>", "    </path>"]
        elif kind == "glow":
            _, cx, cy, r, colour, alpha = layer
            out += [f'    <path android:pathData="{circle_path(cx, cy, r)}">', '        <aapt:attr name="android:fillColor">',
                    f'            <gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}">',
                    f'                <item android:offset="0" android:color="{argb(colour, alpha)}" />',
                    f'                <item android:offset="1" android:color="{argb(colour, 0)}" />',
                    "            </gradient>", "        </aapt:attr>", "    </path>"]
        else:
            _, d, colour, alpha, turn = layer
            fill = f'android:fillColor="{argb(colour)}"' + (f' android:fillAlpha="{alpha}"' if alpha < 1 else "")
            if turn:
                out += [f'    <group android:pivotX="54" android:pivotY="54" android:rotation="{turn}">',
                        f'        <path android:pathData="{d}" {fill} />', "    </group>"]
            else:
                out.append(f'    <path android:pathData="{d}" {fill} />')
    out.append("</vector>")
    return "\n".join(out) + "\n"


def adaptive(icon_id, mono):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/{icon_id}_background" />
    <foreground android:drawable="@drawable/{icon_id}_foreground" />
    <monochrome android:drawable="@drawable/{MONO_FILES[mono]}" />
</adaptive-icon>
"""


def write(path, text):
    with open(path, "w") as file:
        file.write(text)


def write_resources():
    drawable, mipmap = os.path.join(RES, "drawable"), os.path.join(RES, "mipmap-anydpi-v26")
    for icon_id, name, (background, foreground), mono in ICONS:
        write(os.path.join(drawable, f"{icon_id}_background.xml"), vector(background, f"Launcher icon, {name}: its background."))
        write(os.path.join(drawable, f"{icon_id}_foreground.xml"), vector(foreground, f"Launcher icon, {name}: its picture."))
        write(os.path.join(mipmap, f"{icon_id}.xml"), adaptive(icon_id, mono))
    write(os.path.join(mipmap, "ic_launcher_round.xml"), adaptive("ic_launcher", "sun"))
    write(os.path.join(drawable, "ic_launcher_monochrome.xml"), vector(MONO["sun"], "Themed icons and notifications: a sun over a hill, in one colour."))
    write(os.path.join(drawable, "ic_launcher_monochrome_bloom.xml"), vector(MONO["bloom"], "Themed icons, the Bloom designs: the petals in one colour."))

# ---- Preview sheet. --------------------------------------------------------------------------

def svg_layers(layers, key, tint=None):
    out, defs = [], []
    for n, layer in enumerate(layers):
        kind = layer[0]
        if kind == "linear":
            stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in layer[1])
            defs.append(f'<linearGradient id="{key}l{n}" x1="0" y1="0" x2="0" y2="1">{stops}</linearGradient>')
            out.append(f'<rect width="108" height="108" fill="url(#{key}l{n})"/>')
        elif kind == "glow":
            _, cx, cy, r, colour, alpha = layer
            defs.append(f'<radialGradient id="{key}g{n}"><stop offset="0" stop-color="{colour}" stop-opacity="{alpha}"/><stop offset="1" stop-color="{colour}" stop-opacity="0"/></radialGradient>')
            out.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="url(#{key}g{n})"/>')
        else:
            _, d, colour, alpha, turn = layer
            turned = f' transform="rotate({turn} 54 54)"' if turn else ""
            out.append(f'<path d="{d}" fill="{tint or colour}" fill-opacity="{alpha}"{turned}/>')
    return "".join(out), "".join(defs)


def write_sheet(path):
    cell, pad, per_row = 190, 40, 6
    rows = [ICONS[:6], ICONS[6:]]
    width = pad * 2 + per_row * cell
    height = 110 + len(rows) * 2 * (cell + 40)
    body, defs = [], ['<clipPath id="circle"><circle cx="54" cy="54" r="36"/></clipPath>',
                      '<clipPath id="squircle"><rect x="18" y="18" width="72" height="72" rx="21"/></clipPath>']

    def place(x, y, size, clip, inner):
        scale = size / 72
        body.append(f'<g transform="translate({x} {y}) scale({scale}) translate(-18 -18)" clip-path="url(#{clip})">{inner}</g>')

    y = 80
    for row in rows:
        for column, (icon_id, name, (background, foreground), mono) in enumerate(row):
            x = pad + column * cell
            back, back_defs = svg_layers(background, icon_id + "b")
            front, front_defs = svg_layers(foreground, icon_id + "f")
            defs += [back_defs, front_defs]
            place(x + 20, y, 150, "squircle", back + front)
            body.append(f'<text x="{x + 95}" y="{y + 178}" font-size="19" font-weight="600" fill="#111827" text-anchor="middle">{name}</text>')
            # Home-screen size on a dark wallpaper, and the themed icon.
            body.append(f'<rect x="{x + 20}" y="{y + 196}" width="150" height="76" rx="16" fill="#1F2937"/>')
            place(x + 34, y + 210, 48, "circle", back + front)
            themed, _ = svg_layers(MONO[mono], icon_id + "m", tint="#1E3A8A")
            place(x + 106, y + 210, 48, "circle", '<rect width="108" height="108" fill="#D9E2FF"/>' + themed)
        y += 2 * cell - 60
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{y + 20}" viewBox="0 0 {width} {y + 20}" font-family="Helvetica Neue, Helvetica, Arial">'
           f'<defs>{"".join(defs)}</defs><rect width="{width}" height="{y + 20}" fill="#F3F4F7"/>'
           f'<text x="{pad + 20}" y="50" font-size="26" font-weight="700" fill="#111827">Lumen app icons</text>'
           f'{"".join(body)}</svg>')
    write(path, svg)


def write_readme_icon(path):
    """The first icon at 512 px in a squircle, for the README (docs/images/icon.png once rendered)."""
    import math
    points = []
    for step in range(360):
        t = math.radians(step)
        # A superellipse: rounder than a rounded square, squarer than a circle.
        x = 256 + 256 * math.copysign(abs(math.cos(t)) ** 0.5, math.cos(t))
        y = 256 + 256 * math.copysign(abs(math.sin(t)) ** 0.5, math.sin(t))
        points.append(f"{x:.2f},{y:.2f}")
    icon_id, _, (background, foreground), _ = ICONS[0]
    back, back_defs = svg_layers(background, "b")
    front, front_defs = svg_layers(foreground, "f")
    scale = 512 / 72
    write(path, f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">'
                f'<defs>{back_defs}{front_defs}<clipPath id="shape"><polygon points="{" ".join(points)}"/></clipPath></defs>'
                f'<g clip-path="url(#shape)"><g transform="scale({scale}) translate(-18 -18)">{back}{front}</g></g></svg>')


if __name__ == "__main__":
    write_resources()
    if len(sys.argv) > 1:
        write_sheet(sys.argv[1])
    if len(sys.argv) > 2:
        write_readme_icon(sys.argv[2])
