"""
Generate ui/icons/LumenIcons.kt from Fluent UI System Icons SVGs (MIT, Microsoft).

Only the icons Lumen uses are converted, so the app doesn't ship a whole icon library.
Usage: python3 build_icons.py tools/icons/svg app/src/main/java/com/subhashh/lumen/ui/icons/LumenIcons.kt
The SVGs are kept in tools/icons/svg (MIT) so the icon set can be regenerated offline.
"""
import re
import sys

# Kotlin name -> Fluent file stem (without size/style). Style is picked per entry.
ICONS = [
    ("Library", "image_multiple", "regular"),
    ("LibraryFilled", "image_multiple", "filled"),
    ("Collections", "album", "regular"),
    ("CollectionsFilled", "album", "filled"),
    ("Search", "search", "regular"),
    ("SearchFilled", "search", "filled"),
    ("Back", "chevron_left", "filled"),
    ("Share", "share_ios", "regular"),
    ("Heart", "heart", "regular"),
    ("HeartFilled", "heart", "filled"),
    ("Info", "info", "regular"),
    ("Delete", "delete", "regular"),
    ("DeleteForever", "delete_dismiss", "regular"),
    ("Restore", "arrow_undo", "regular"),
    ("Play", "play", "filled"),
    ("Pause", "pause", "filled"),
    ("Folder", "folder", "regular"),
    ("Video", "video", "regular"),
    ("Screenshot", "phone", "regular"),
    ("Camera", "camera", "regular"),
    ("Image", "image", "regular"),
    ("Location", "location", "regular"),
    ("Selected", "checkmark_circle", "filled"),
    ("Unselected", "circle", "regular"),
    ("Close", "dismiss", "regular"),
    ("Filter", "filter", "regular"),
    ("Settings", "settings", "regular"),
    ("Check", "checkmark", "regular"),
    ("More", "more_vertical", "regular"),
    ("Add", "add", "regular"),
    ("NewAlbum", "folder_add", "regular"),
    ("Lock", "lock_closed", "regular"),
    ("Unhide", "eye", "regular"),
    ("Hide", "eye_off", "regular"),
    ("Edit", "edit", "regular"),
    ("LiveText", "scan_text", "regular"),
    ("LiveTextFilled", "scan_text", "filled"),
]

src_dir, out = sys.argv[1], sys.argv[2]
entries = []
for kotlin_name, stem, style in ICONS:
    svg = open(f"{src_dir}/ic_fluent_{stem}_24_{style}.svg", encoding="utf-8").read()
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths:
        sys.exit(f"no paths in {stem} {style}")
    rules = re.findall(r'<path[^>]*fill-rule="([^"]+)"', svg)
    even_odd = "evenodd" in rules
    entries.append((kotlin_name, f"{stem}_{style}", paths, even_odd))

lines = [
    "// Generated by tools/icons/build_icons.py — do not edit by hand.",
    "// Icons: Fluent UI System Icons, Copyright (c) Microsoft Corporation, MIT License.",
    "package com.subhashh.lumen.ui.icons",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.graphics.PathFillType",
    "import androidx.compose.ui.graphics.SolidColor",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "import androidx.compose.ui.graphics.vector.addPathNodes",
    "import androidx.compose.ui.unit.dp",
    "",
    "/** Lumen's icon set: Fluent outline icons, with filled variants for selected/active states. */",
    "object LumenIcons {",
]
for kotlin_name, vector_name, paths, even_odd in entries:
    args = ", ".join(f'"{p}"' for p in paths)
    lines.append(f'    val {kotlin_name}: ImageVector by lazy {{ fluent("{vector_name}", {str(even_odd).lower()}, {args}) }}')
lines += [
    "}",
    "",
    "private fun fluent(name: String, evenOdd: Boolean, vararg paths: String): ImageVector =",
    "    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {",
    "        for (d in paths) {",
    "            addPath(",
    "                pathData = addPathNodes(d),",
    "                fill = SolidColor(Color.Black),",
    "                pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,",
    "            )",
    "        }",
    "    }.build()",
    "",
]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(f"wrote {len(entries)} icons to {out}")
