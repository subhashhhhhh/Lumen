/** Lumen Lab's repository, when it's checked out next to this one (see sourceSets below). */
val lab: File = rootProject.file("../lumen-lab")
val hasLab = lab.resolve("src/java").isDirectory

/**
 * The release key stays outside the repository. Release builds are signed only when its password
 * is given, e.g. LUMEN_KEY_PASSWORD from the macOS Keychain; otherwise they come out unsigned.
 */
val releaseKeyPassword: String? = providers.environmentVariable("LUMEN_KEY_PASSWORD").orNull
val releaseKeyStore: File = providers.environmentVariable("LUMEN_KEYSTORE").orNull?.let(::File)
    ?: File(System.getProperty("user.home"), ".lumen-signing/lumen-release.jks")

android {
    namespace = "com.subhashh.lumen"
    compileSdk = 37

    defaultConfig {
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        applicationId = "com.subhashh.lumen"
        // Android 11: All files access (hidden folders) and MediaStore trash.
        minSdk = 30
        targetSdk = 37
        versionCode = 11
        versionName = "0.4.0"
    }

    signingConfigs {
        if (releaseKeyPassword != null) {
            create("release") {
                storeFile = releaseKeyStore
                storePassword = releaseKeyPassword
                keyAlias = "lumen"
                keyPassword = releaseKeyPassword
            }
        }
    }

    // Release APKs per processor, plus one universal APK. Only for release tasks, so debug and
    // profile builds stay a single APK.
    splits {
        abi {
            isEnable = gradle.startParameter.taskNames.any { it.contains("Release", ignoreCase = true) }
            reset()
            include("arm64-v8a", "armeabi-v7a", "x86_64")
            isUniversalApk = true
        }
    }

    // 32-bit x86 Android 11+ devices don't exist in practice; its libraries only bloated the
    // universal APK (~50 MB).
    packaging {
        jniLibs { excludes += "lib/x86/**" }
    }

    buildTypes {
        release {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
        debug {
            applicationIdSuffix = ".debug"
            // With the Lab: arm64 only, or its native runtimes add ~150 MB.
            if (hasLab) ndk { abiFilters += "arm64-v8a" }
        }
        // Release-optimized (R8, not debuggable) but debug-signed, for judging smoothness on the
        // phone: Compose debug builds run several times slower. Same app id as debug, so it
        // installs over it and keeps granted permissions.
        create("profile") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            applicationIdSuffix = ".debug"
            matchingFallbacks += listOf("release")
            if (hasLab) {
                proguardFiles(lab.resolve("lab-rules.pro"))
                ndk { abiFilters += "arm64-v8a" }
            }
        }
    }

    // Lumen Lab (model head-to-heads and speed tests) lives in its own repository. Checked out
    // next to this one as ../lumen-lab, it's built into debug and profile builds; never release.
    if (hasLab) {
        sourceSets {
            getByName("debug").kotlin.directories.add(lab.resolve("src/java").path)
            getByName("profile").kotlin.directories.add(lab.resolve("src/java").path)
            getByName("debug").manifest.srcFile(lab.resolve("manifests/debug/AndroidManifest.xml"))
            getByName("profile").manifest.srcFile(lab.resolve("manifests/profile/AndroidManifest.xml"))
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // Per-app language (Android 13+, Settings → Apps → Lumen → Language): the list of languages is
    // generated from the translated res/values-xx folders; res/resources.properties says the
    // default strings are English.
    androidResources {
        generateLocaleConfig = true
    }
}

